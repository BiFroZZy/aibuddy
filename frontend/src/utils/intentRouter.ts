export interface IntentResult {
  message: string;
  sourceCard?: SourceDoc;
  showForm?: 'absence' | 'access';
  actions?: Array<{ label: string; action: () => void }>;
}

export function routeIntent(text: string, nextTask: string, setView: (view: ViewId) => void): IntentResult {
  const q = text.toLowerCase();

  // Refusal patterns
  if (/чуж|другой команд|другую команд|зарплат|персональн|секрет|обой[тд]|игнорир/.test(q)) {
    return {
      message: 'В доступных учебных источниках нет подтверждённого ответа. Обсуди рабочий вопрос с наставником.',
      sourceCard: sourceDocs.mentor,
      actions: [{ label: 'Контакт наставника →', action: () => routeIntent('Кто мой наставник?', nextTask, setView) }],
    };
  }

  // Leave/absence
  if (/отгул|отсутств|отпуск/.test(q)) {
    return {
      message: 'В учебном порядке отгул требует согласования. Укажи даты и короткий комментарий, затем проверь и подтверди заявку.',
      sourceCard: sourceDocs.absence,
      showForm: 'absence',
    };
  }

  // Access/repo
  if (/доступ|репозитор/.test(q)) {
    return {
      message: 'Подготовим запрос на чтение учебного репозитория. Укажи, для какой задачи нужен доступ. Сначала проверим данные, затем попросим твоё подтверждение.',
      sourceCard: sourceDocs.access,
      showForm: 'access',
    };
  }

  // Mentor/team
  if (/наставник|связаться|команд/.test(q)) {
    return {
      message: 'Твой демо-наставник — Мария, backend-разработчик. Канал для рабочих вопросов: #backend-interns. Обсуди с ней цели первой недели и критерии готовности первой задачи. Сообщения из прототипа не отправляются.',
      sourceCard: sourceDocs.mentor,
    };
  }

  // Tasks/plan
  if (/задач/.test(q)) {
    return {
      message: 'Первая учебная задача — разобраться с обработчиком /health. Перед началом проверь доступы и окружение. Результат и время ревью согласуй с наставником.',
      sourceCard: sourceDocs.mentor,
    };
  }

  // Local run/readme
  if (/запуст|окружен|локально|документац/.test(q)) {
    return {
      message: 'Начни с доступа к учебному репозиторию, затем изучи README и подготовь окружение. Точные команды нужно брать из README самого проекта: в этой демо-базе их нет.',
      sourceCard: sourceDocs.readme,
    };
  }

  // Next step/week/progress
  if (/начать|недел|дальше|шаг|привет|прогресс/.test(q)) {
    return {
      message: nextTask,
      sourceCard: sourceDocs.plan,
      actions: [{ label: 'Открыть план →', action: () => setView('plan') }],
    };
  }

  // Prototype info
  if (/прототип|умеет/.test(q)) {
    return {
      message: 'Это демонстрационный прототип AI-buddy для стажёров Авито. Он умеет: отвечать на вопросы по учебным материалам, готовить заявки на отгул и доступы, вести план адаптации, хранить историю действий. Реальные корпоративные сервисы не подключены.',
    };
  }

  // Default fallback
  return {
    message: 'Не совсем понял. Попробуй спросить про отгул, доступ к репозиторию, первую задачу или наставника.',
  };
}

export type ViewId = 'home' | 'plan' | 'materials' | 'requests';